from datetime import datetime
from typing import Optional
from pydantic import BaseModel, Field, ConfigDict
from pydantic.alias_generators import to_camel

class IncidentProposal(BaseModel):
    """
    Extracted the incident proposal generated by the LLM from unstructured alert text.
    Serializes to camelCase to match Java incident-svc's IncidentRequest record.
    """
    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True)

    # 1. Operation Metadata
    title: str = Field(description="Short summary of the incident")
    service_id: str = Field(description="Identifier of the affected service or databases")
    severity_hint: Optional[str] = Field(default=None, description="Reported severity, e.g. P1, P2, CRITICAL")

    # 2. The 7 RTS (EU 2024/1772) Criteria
    is_critical_service: bool = Field(description="Identify if the service is critical or not")
    affected_clients_count: Optional[int] = Field(default=None, description="Number of unique clients affected. Never equate transaction/attempt counts with client count. Set to None if unknown.")
    duration_minutes: Optional[int] = Field(default=None, description="Downtime or service degradation in integer minutes (e.g. '3 hours' -> 180).")
    economic_impact_amount: Optional[float] = Field(default=None, description="Estimated direct financial loss or transaction amount in EUR as a raw number without currency symbols (e.g. '€450,000' -> 450000.0)")
    data_integrity_impacted: bool = Field(default=False, description="Identifier if the data integrity is impacted or not")
    reputational_impact: Optional[bool] = Field(default=False, description="Identifier for if the reputation impacted")
    geographic_spread_count: int = Field(default=1, description="How many countries which has been affected")
    affected_clients_percentage: Optional[float] = Field(default=None, description="Percentage of total client base affected (e.g., 10.5 for 10.5%), if explicitly stated.")

    # 3. Model Reasoning (Crucial for auditability)
    extraction_reasoning: str = Field(default="", description="Explanation of how the metrics were extracted from the text")
